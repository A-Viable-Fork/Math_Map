// Role: the gap finder. Over every entry the free typing pass types (scripts/type-lexicon.mjs), finds the kinds no
//   operation produces, the kinds none consumes, and the major kinds no chain of operations reaches: the shape of
//   what the map is missing, each gap a typed question for generation (Research_OS BLUEPRINT.md, section 12b).
// Contract: `node scripts/gaps.mjs` writes reports/GAPS.md; `--check` prints it without writing; exports gaps(P?).
//   An operation counts when both its input and its output carry at least one adopted kind. Producing a kind
//   produces its parents (a distribution is a measure). A gap is a lead: it may be a typing miss (the operation is
//   in the map, its other side untyped), a coarse kind, or mathematics the map lacks; only reading tells which.
// Invariant: read-only. Inherits the typing pass's precision (about 9 in 10 operands right on its graded sample).
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "./mathmap.mjs";
import { typeEntries } from "./type-lexicon.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MAJOR = ["space", "category", "group", "manifold", "graph", "function", "matrix", "ring", "sequence", "variety", "poset", "algebra", "module", "simplicial-set", "sheaf", "measure", "process", "chain-complex", "formula", "knot", "signal", "equation"];

export function gaps(P = parse()) {
  const C = P.vocabulary.CARRIERS, ok = (k) => k && k !== "parameter" && k in C;
  const up = (k) => { const out = [k]; for (let x = C[k]; x; x = C[x]) out.push(x); return out; };
  const ops = typeEntries(P).map((t) => ({ id: t.id, in: [...new Set(t.input.map((x) => x.kind).filter(ok))], out: [...new Set(t.output.map((x) => x.kind).filter(ok))] })).filter((o) => o.in.length && o.out.length);
  const kinds = [...new Set(ops.flatMap((o) => [...o.in, ...o.out]))].sort();
  const prod = {}, cons = {};
  for (const o of ops) { for (const k of o.out.flatMap(up)) (prod[k] ||= []).push(o.id); for (const k of o.in) (cons[k] ||= []).push(o.id); }
  const adj = {};
  for (const o of ops) for (const a of o.in) for (const b of o.out) for (const c of up(b)) (adj[a] ||= new Set()).add(c);
  const reach = (s) => { const seen = new Set([s]), q = [s]; while (q.length) { const x = q.shift(); for (const y of adj[x] || []) if (!seen.has(y)) { seen.add(y); q.push(y); } } return seen; };
  const major = MAJOR.filter((k) => kinds.includes(k));
  const unreachable = major.map((k) => ({ kind: k, from: major.filter((a) => a !== k && !reach(a).has(k)) })).filter((u) => u.from.length);
  return {
    ops: ops.length, entries: P.entries.length, kinds,
    neverProduced: kinds.filter((k) => !prod[k]).map((k) => ({ kind: k, consumedBy: (cons[k] || []).length })),
    neverConsumed: kinds.filter((k) => !cons[k] && !kinds.some((c) => cons[c] && up(c).includes(k) && c !== k)).map((k) => ({ kind: k, producedBy: (prod[k] || []).length })),
    unreachable,
  };
}

export function render(G) {
  const L = ["# Gaps in the typed map", "",
    "Generated by `scripts/gaps.mjs` over the entries the free typing pass types (`reports/TYPING.md`). Each gap is a typed question: a kind nothing makes, a kind nothing uses, a kind no chain reaches. A gap may be a typing miss, a coarse kind, or mathematics the map lacks; only reading tells which.", "",
    `Operations typed on both sides: ${G.ops} of ${G.entries} entries; kinds in use: ${G.kinds.length}.`, "",
    "## Kinds no operation produces", "", ...(G.neverProduced.length ? G.neverProduced.map((g) => `- ${g.kind} (consumed by ${g.consumedBy})`) : ["None."]), "",
    "## Kinds no operation consumes", "", ...(G.neverConsumed.length ? G.neverConsumed.map((g) => `- ${g.kind} (produced by ${g.producedBy})`) : ["None."]), "",
    "## Major kinds some major kinds cannot reach", "", ...(G.unreachable.length ? G.unreachable.map((u) => `- ${u.kind}, from: ${u.from.join(", ")}`) : ["None."])];
  return L.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render(gaps());
  if (process.argv.includes("--check")) console.log(out);
  else { writeFileSync(join(ROOT, "reports/GAPS.md"), out + "\n"); console.log("wrote reports/GAPS.md"); }
}
